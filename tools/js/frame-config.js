// Frame configuration schema: matches firmware Settings and Gallery::loadSettings.
export const FRAME_DEFAULTS = Object.freeze({
  orientation:0, refresh_minutes:720, shuffle:false,
  quiet_hours_start:'00:00', quiet_hours_end:'00:00',
  activity_led:true, usb_auto_next:false, image_fit:'contain',
  progressive_jpeg:'preview', cache_enabled:true, skip_unchanged:true,
  single_image_auto_pause:true, cache_write_min_v:3.6,
  battery_calibration:1, low_battery_v:3.4, critical_cutoff_v:3.1
});
const KEYS=Object.keys(FRAME_DEFAULTS);
export function validateFrame(input){
  const o={...FRAME_DEFAULTS},errors=[];
  for(const key of KEYS){
    if(!Object.hasOwn(input,key))continue;
    let value=input[key];const sample=FRAME_DEFAULTS[key];
    if(typeof sample==='boolean'){
      if(typeof value==='string'){if(['true','1','on'].includes(value.toLowerCase()))value=true;
      else if(['false','0','off'].includes(value.toLowerCase()))value=false;
      else {errors.push(key+': booléen incorrect');continue;}}
      if(typeof value!=='boolean'){errors.push(key+': booléen incorrect');continue;}
    }else if(typeof sample==='number'){
      if(String(value).trim()==='') {errors.push(key+': nombre manquant');continue;}
      value=Number(value);if(!Number.isFinite(value)){errors.push(key+': nombre incorrect');continue;}
    }else value=String(value).trim();
    o[key]=value;
  }
  const clock=v=>/^([01]\d|2[0-3]):[0-5]\d$/.test(v);
  if(![0,90,180,270].includes(o.orientation))errors.push('orientation: 0/90/180/270');
  if(!Number.isInteger(o.refresh_minutes)||o.refresh_minutes<1||o.refresh_minutes>10080)errors.push('refresh_minutes: 1..10080');
  if(!clock(o.quiet_hours_start)||!clock(o.quiet_hours_end))errors.push('Horaires: HH:MM (24h)');
  if(!['contain','cover'].includes(o.image_fit))errors.push('image_fit: contain/cover');
  if(!['preview','reject'].includes(o.progressive_jpeg))errors.push('progressive_jpeg: preview/reject');
  for(const [key,min,max] of [['cache_write_min_v',3.3,4.2],['low_battery_v',3.2,3.8],['critical_cutoff_v',3,3.4],['battery_calibration',.85,1.15]]){
    if(o[key]<min||o[key]>max)errors.push(key+`: ${min}..${max}`);
  }
  if(o.critical_cutoff_v>=o.low_battery_v)errors.push('Le seuil critique doit être inférieur au seuil bas');
  if(o.cache_write_min_v<o.low_battery_v+.1-1e-6)errors.push('Seuil cache ≥ seuil bas + 0.10 V');
  return {settings:o,errors};
}
export function serializeFrame(value){
  const {settings:s,errors}=validateFrame(value);
  if(errors.length)throw Error(errors.join(' ; '));
  const lines=[
    '# PhotoPainter RP2040 settings.conf — generated by PhotoPainter Studio',
    '# Physical AUTO-NEXT slider gates RTC wake on battery.',
    '# Quiet hours: equal times disable the rule; crossing midnight supported.',
  ];
  for(const key of KEYS){const v=s[key];lines.push(`${key}=${typeof v==='boolean'?String(v):v}`);}
  return lines.join('\n')+'\n';
}
export function parseFrame(text){
  const data={},unknown=[];
  for(const line of text.split(/\r?\n/)){
    const trim=line.trim();if(!trim||trim[0]==='#'||trim[0]===';')continue;
    const equal=trim.indexOf('=');if(equal<1)continue;
    const key=trim.slice(0,equal).trim().toLowerCase();
    if(!KEYS.includes(key)){unknown.push(key);continue;}
    data[key]=trim.slice(equal+1).trim().replace(/\s+[;#].*$/,'');
  }
  const {settings,errors}=validateFrame(data);
  return {settings,errors,unknown};
}
